const whatsappPhone = "59895018460";
const grid = document.getElementById("products-grid");

function formatMoney(value, decimals) {
  const options = {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals
  };
  return "$ " + Number(value).toLocaleString("es-UY", options);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[character]);
}

function orderUrl(product, variant) {
  const selected = variant || product;
  const presentation = variant ? "Presentación en caja de " : "";
  const message = [
    "Hola, quisiera consultar por la " + presentation + product.title + ".",
    "Código: " + selected.code + ".",
    "Precio: " + formatMoney(selected.price, 0) + " IVA incluido."
  ].join(" ");
  return "https://api.whatsapp.com/send?phone=" + whatsappPhone + "&text=" + encodeURIComponent(message);
}

function renderVariant(product, variant) {
  const image = variant.image
    ? '<img class="variant-image" src="' + escapeHtml(variant.image) + '" alt="Presentación en caja de la canasta Nº ' + escapeHtml(product.number) + '" loading="lazy">'
    : '<span class="variant-symbol" aria-hidden="true">▱</span>';
  const netDecimals = Number.isInteger(variant.netPrice) ? 0 : 2;

  return '<div class="variant' + (variant.image ? "" : " no-image") + '">' +
    image +
    '<div class="variant-copy">' +
      '<p class="variant-label">' + escapeHtml(variant.label) + '</p>' +
      '<p class="variant-code">Código ' + escapeHtml(variant.code) + '</p>' +
      '<span class="variant-price">' + formatMoney(variant.price, 0) + ' <span class="tax-note">IVA incl.</span></span>' +
      '<span class="variant-net">' + formatMoney(variant.netPrice, netDecimals) + ' + IVA</span>' +
      '<a class="variant-order" href="' + escapeHtml(orderUrl(product, variant)) + '" target="_blank" rel="noopener noreferrer">Consultar esta presentación</a>' +
    '</div>' +
  '</div>';
}

function renderProduct(product) {
  const netDecimals = Number.isInteger(product.netPrice) ? 0 : 2;
  const items = product.items.map(item => "<li>" + escapeHtml(item) + "</li>").join("");
  const variants = product.variants
    ? '<div class="variant-list" aria-label="Presentaciones alternativas">' +
        product.variants.map(variant => renderVariant(product, variant)).join("") +
      '</div>'
    : "";
  const itemLabel = product.items.length === 1 ? "producto" : "productos";

  return '<article class="product-card">' +
    '<div class="product-image-wrap">' +
      '<img class="product-image" src="' + escapeHtml(product.image) + '" alt="' + escapeHtml(product.title + " con los productos incluidos") + '" loading="lazy">' +
      '<span class="product-code">CÓDIGO ' + escapeHtml(product.code) + '</span>' +
    '</div>' +
    '<div class="product-content">' +
      '<h3 class="product-title">' + escapeHtml(product.title) + '</h3>' +
      '<div class="price-row">' +
        '<span class="price-label">Precio de catálogo<br><span class="tax-note">IVA incluido</span></span>' +
        '<span class="price">' + formatMoney(product.price, 0) + '</span>' +
      '</div>' +
      '<p class="tax-note">Neto: ' + formatMoney(product.netPrice, netDecimals) + ' + IVA</p>' +
      '<details class="included">' +
        '<summary>Ver contenido (' + product.items.length + ' ' + itemLabel + ')</summary>' +
        '<ul>' + items + '</ul>' +
      '</details>' +
      variants +
      '<div class="product-actions">' +
        '<a class="button-primary" href="' + escapeHtml(orderUrl(product)) + '" target="_blank" rel="noopener noreferrer">Consultar canasta por WhatsApp</a>' +
      '</div>' +
    '</div>' +
  '</article>';
}

if (grid) {
  grid.innerHTML = catalog.map(renderProduct).join("");
}
